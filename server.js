#!/usr/bin/env node
import { existsSync, readFileSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";

// Works both inside the repo (../site) and when published to npm (./lib, ./icons.json).
const here = (p) => new URL(p, import.meta.url);
const packed = existsSync(here("./lib/icon.js"));
const { cleanIcon, generateIcon } = await import(packed ? "./lib/icon.js" : "../site/lib/icon.js");
const baseIcons = JSON.parse(readFileSync(here(packed ? "./icons.json" : "../site/icons.json"), "utf8")).map(cleanIcon);

// Icons generated by this server are kept on the user's machine.
const CUSTOM_FILE = process.env.IKONIA_CUSTOM_ICONS || join(homedir(), ".ikonia", "icons.json");
let custom = [];
try { custom = JSON.parse(readFileSync(CUSTOM_FILE, "utf8")).map(cleanIcon); } catch {}
const icons = [...baseIcons];
for (const c of custom) if (!icons.some((i) => i.name === c.name)) icons.push(c);

function score(i, t) {
  const w = i.tags.split(" ");
  if (i.name === t) return 4;
  if (i.name.startsWith(t)) return 3;
  if (w.includes(t)) return 2.5;
  if (w.some((k) => k.startsWith(t))) return 1.5;
  return (i.name + " " + i.tags).includes(t) ? 0.5 : 0;
}
function search(query, limit) {
  const t = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  return icons
    .map((i) => [i, t.reduce((a, w) => a + score(i, w), 0)])
    .filter((p) => p[1] > 0)
    .sort((a, b) => b[1] - a[1])
    .slice(0, limit)
    .map((p) => p[0]);
}

const COLOR = z.string().regex(/^[#a-zA-Z0-9(),.%\s-]{1,40}$/, "Use a CSS color such as currentColor, #111 or rgb(0,0,0)");
function render(icon, { style, size, color, background, format }) {
  const solid = style === "solid";
  const react = format === "react";
  const attr = (a, b) => (react ? a : b);
  const f = icon.f.map((d) => `<path d="${d}"${solid ? ` fill="${color}"` : ""} />`).join("");
  const l = icon.l ? `<path d="${icon.l}"${solid ? ` stroke="${background}"` : ""} />` : "";
  const x = icon.x ? `<path d="${icon.x}" />` : "";
  const open = `<svg ${react ? "" : 'xmlns="http://www.w3.org/2000/svg" '}viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="${color}" ${attr("strokeWidth", "stroke-width")}="1.75" ${attr("strokeLinecap", "stroke-linecap")}="round" ${attr("strokeLinejoin", "stroke-linejoin")}="round"${react ? " {...props}" : ""}>`;
  const body = `${open}${f}${l}${x}</svg>`;
  if (!react) return body;
  const comp = icon.name.split("-").map((s) => s[0].toUpperCase() + s.slice(1)).join("") + "Icon";
  return `export function ${comp}(props) {\n  return (\n    ${body}\n  );\n}`;
}
const text = (t, isError = false) => ({ content: [{ type: "text", text: t }], ...(isError ? { isError: true } : {}) });

const server = new McpServer({ name: "ikonia", version: "0.1.0" });

server.registerTool(
  "search_icons",
  {
    title: "Search icons",
    description: "Search the icon library by meaning (e.g. 'save to device', 'money', 'security'). Returns icon names with related keywords. Call get_icon next to get the SVG.",
    inputSchema: { query: z.string().min(1).max(80), limit: z.number().int().min(1).max(30).default(8) },
    annotations: { readOnlyHint: true, openWorldHint: false },
  },
  async ({ query, limit }) => {
    const hits = search(query, limit);
    if (!hits.length) return text(`No icons match "${query}". Try a broader word, or call generate_icon to create one.`);
    return text(hits.map((i) => `${i.name}: ${i.tags}`).join("\n"));
  }
);

server.registerTool(
  "get_icon",
  {
    title: "Get icon code",
    description: "Return an icon as ready-to-paste code. Use format 'svg' for plain SVG or 'react' for a React component. Style 'solid' fills the shapes; 'background' is the colour used for cut-out details in solid style and should match the surface the icon sits on.",
    inputSchema: {
      name: z.string().min(1).max(40),
      style: z.enum(["outline", "solid"]).default("outline"),
      format: z.enum(["svg", "react"]).default("svg"),
      size: z.number().int().min(8).max(512).default(24),
      color: COLOR.default("currentColor"),
      background: COLOR.default("#ffffff"),
    },
    annotations: { readOnlyHint: true, openWorldHint: false },
  },
  async ({ name, ...opts }) => {
    const icon = icons.find((i) => i.name === name.toLowerCase().trim());
    if (!icon) {
      const near = search(name, 5).map((i) => i.name);
      return text(`No icon named "${name}".${near.length ? ` Closest matches: ${near.join(", ")}.` : " Use search_icons to find one."}`, true);
    }
    return text(render(icon, opts));
  }
);

server.registerTool(
  "generate_icon",
  {
    title: "Generate a new icon",
    description: "Create a new icon with Claude when search_icons finds nothing suitable. The icon is saved on this machine and becomes available to search_icons and get_icon. Requires ANTHROPIC_API_KEY in the server's environment and uses API credits, so call it only when needed.",
    inputSchema: { concept: z.string().min(2).max(60) },
    annotations: { readOnlyHint: false, idempotentHint: false, openWorldHint: true },
  },
  async ({ concept }) => {
    const key = process.env.ANTHROPIC_API_KEY;
    if (!key) return text("generate_icon needs ANTHROPIC_API_KEY set in this MCP server's environment (add it under \"env\" in the MCP config).", true);
    let icon;
    try { icon = await generateIcon(key, concept); }
    catch (e) { return text(`Could not generate a usable icon for "${concept}": ${e.message}`, true); }
    if (icons.some((i) => i.name === icon.name)) return text(`An icon named "${icon.name}" already exists. Use get_icon with that name.`);
    icons.push(icon);
    custom.push(icon);
    let saved = `Saved to ${CUSTOM_FILE}.`;
    try { await mkdir(dirname(CUSTOM_FILE), { recursive: true }); await writeFile(CUSTOM_FILE, JSON.stringify(custom, null, 1)); }
    catch { saved = "Could not save to disk; it is available until the server restarts."; }
    return text(`Created "${icon.name}" (tags: ${icon.tags}). ${saved}\n\n${render(icon, { style: "outline", size: 24, color: "currentColor", background: "#ffffff", format: "svg" })}`);
  }
);

await server.connect(new StdioServerTransport());
